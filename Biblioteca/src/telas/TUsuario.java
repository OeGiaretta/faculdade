    public void salvar() {
        Usuario u = new Usuario();
        u.setCodusuario(Integer.parseInt(campo2.getText()));
        u.setNome(campo8.getText().toUpperCase());
        u.setLogin(campo6.getText().toUpperCase());    
        u.setSenha(new String(jPasswordField1.getPassword()).toUpperCase());

        try {
            dao.salvar(u);
            JOptionPane.showMessageDialog(null, "USUÁRIO SALVO COM SUCESSO");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e, "ERRO", JOptionPane.ERROR_MESSAGE);
        }
        limpar();
    }

    public void consultar() {
        int chave = Integer.parseInt(campo2.getText());
        Object obj1 = new Object();
        try {
            obj1 = dao.consultar("Usuario.findByCodusuario", "codusuario", chave);
            Usuario u = (Usuario) obj1;
            campo8.setText(u.getNome());
            campo6.setText(u.getLogin());
            jPasswordField1.setText(u.getSenha());
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "USUÁRIO NÃO EXISTE", "ERRO", 0);
        }
    }

    public void excluir() {
        int chave = Integer.parseInt(campo2.getText());
        try {
            dao.excluir("Usuario.findByCodusuario", "codusuario", chave);
            JOptionPane.showMessageDialog(null, "USUÁRIO EXCLUIDO COM SUCESSO");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "USUÁRIO NÃO EXISTE", "ERRO", 0);
        }
        limpar();
    }

    public void limpar() {
        campo2.setText("");
        campo6.setText("");
        jPasswordField1.setText("");
        campo8.setText("");
    }

    public void sair() {
        dispose();
    }
