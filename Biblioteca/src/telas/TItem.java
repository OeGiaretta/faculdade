    public void salvar() {
        try {
            
            if (campo12.getText().trim().isEmpty()) {
                JOptionPane.showMessageDialog(
                        null,
                        "INFORME UM ID VÁLIDO.",
                        "ID INVÁLIDO",
                        JOptionPane.WARNING_MESSAGE
                );
                return;
            }

            int iditem = Integer.parseInt(campo12.getText().trim());

            
            if (iditem <= 0) {
                JOptionPane.showMessageDialog(
                        null,
                        "O ID DEVE SER UM NÚMERO MAIOR QUE ZERO.",
                        "ID INVÁLIDO",
                        JOptionPane.WARNING_MESSAGE
                );
                return;
            }

            Item p = new Item();

            p.setIditem(iditem);
            p.setTitulo(campo10.getText().toUpperCase());
            p.setQuantidade(Integer.parseInt(campo8.getText()));
            p.setIdtipoitem(Integer.parseInt(campo7.getText()));
            p.setIdclassificacao(Integer.parseInt(campo6.getText()));
            p.setSituacao(campo13.getText().toUpperCase());

            dao.salvar(p);

            
            if (p.getIdtipoitem() == 1) {

                Livro livro = new Livro();

                livro.setIditem(p.getIditem());
                livro.setAutor(campo14.getText().toUpperCase());
                livro.setEditora(campo15.getText().toUpperCase());
                livro.setAnopublicacao(
                        Integer.parseInt(campo16.getText())
                );

                dao.salvar(livro);

            } else if (p.getIdtipoitem() == 2) {

                Periodico periodico = new Periodico();

                periodico.setIditem(p.getIditem());
                periodico.setNumexemplar(
                        Integer.parseInt(campo17.getText())
                );

                dao.salvar(periodico);
            }

            JOptionPane.showMessageDialog(
                    null,
                    "ITEM SALVO COM SUCESSO",
                    "SUCESSO",
                    JOptionPane.INFORMATION_MESSAGE
            );

            limpar();

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                    null,
                    "VERIFIQUE OS CAMPOS NUMÉRICOS.\n"
                    + "O ID, quantidade, tipo, classificação e demais campos numéricos "
                    + "devem conter apenas números.",
                    "ERRO DE PREENCHIMENTO",
                    JOptionPane.ERROR_MESSAGE
            );

        } catch (Exception e) {

            JOptionPane.showMessageDialog(
                    null,
                    "ERRO AO SALVAR O ITEM\n",
                    "ERRO",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }

    public void consultar() {
        try {
            
            if (campo12.getText().trim().isEmpty()) {
                JOptionPane.showMessageDialog(
                        null,
                        "INFORME UM ID VÁLIDO PARA CONSULTAR.",
                        "ID INVÁLIDO",
                        JOptionPane.WARNING_MESSAGE
                );
                return;
            }

            int chave = Integer.parseInt(campo12.getText().trim());

            
            if (chave <= 0) {
                JOptionPane.showMessageDialog(
                        null,
                        "O ID DEVE SER UM NÚMERO MAIOR QUE ZERO.",
                        "ID INVÁLIDO",
                        JOptionPane.WARNING_MESSAGE
                );
                return;
            }

            Object obj1 = dao.consultar(
                    "Item.findByIditem",
                    "iditem",
                    chave
            );

            
            if (obj1 == null) {
                JOptionPane.showMessageDialog(
                        null,
                        "NENHUM ITEM FOI ENCONTRADO COM O ID " + chave + ".",
                        "ITEM NÃO ENCONTRADO",
                        JOptionPane.WARNING_MESSAGE
                );
                return;
            }

            Item p = (Item) obj1;

            campo10.setText(p.getTitulo());
            campo8.setText(Integer.toString(p.getQuantidade()));
            campo7.setText(Integer.toString(p.getIdtipoitem()));
            campo6.setText(Integer.toString(p.getIdclassificacao()));
            campo13.setText(p.getSituacao());

            
            if (p.getIdtipoitem() == 1) {

                obj1 = dao.consultar(
                        "Livro.findByIditem",
                        "iditem",
                        chave
                );

                if (obj1 != null) {
                    Livro livro = (Livro) obj1;

                    campo14.setText(livro.getAutor());
                    campo15.setText(livro.getEditora());
                    campo16.setText(
                            Integer.toString(livro.getAnopublicacao())
                    );
                }

            } else if (p.getIdtipoitem() == 2) {

                obj1 = dao.consultar(
                        "Periodico.findByIditem",
                        "iditem",
                        chave
                );

                if (obj1 != null) {
                    Periodico periodico = (Periodico) obj1;

                    campo17.setText(
                            Integer.toString(periodico.getNumexemplar())
                    );
                }
            }

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                    null,
                    "O ID INFORMADO É INVÁLIDO.\n"
                    + "DIGITE APENAS NÚMEROS.",
                    "ID INVÁLIDO",
                    JOptionPane.ERROR_MESSAGE
            );

        } catch (Exception e) {

            JOptionPane.showMessageDialog(
                    null,
                    "ERRO AO CONSULTAR O ITEM\n",
                    "ERRO",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }

    public void excluir() {
        try {

            int chave = Integer.parseInt(campo12.getText().trim());

            
            Item item = (Item) dao.consultar(
                    "Item.findByIditem",
                    "iditem",
                    chave
            );

            
            if (item == null) {
                JOptionPane.showMessageDialog(
                        null,
                        "NENHUM ITEM FOI ENCONTRADO COM O ID " + chave + ".",
                        "ITEM NÃO ENCONTRADO",
                        JOptionPane.WARNING_MESSAGE
                );
                return;
            }

            int tipo = item.getIdtipoitem();

            
            if (tipo == 1) {
                dao.excluir("Livro.findByIditem", "iditem", chave);

            } else if (tipo == 2) {
                dao.excluir("Periodico.findByIditem", "iditem", chave);
            }

            
            dao.excluir("Item.findByIditem", "iditem", chave);

            JOptionPane.showMessageDialog(
                    null,
                    "ITEM EXCLUÍDO COM SUCESSO"
            );

            limpar();

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                    null,
                    "INFORME UM ID VÁLIDO.",
                    "ERRO",
                    JOptionPane.ERROR_MESSAGE
            );

        } catch (Exception e) {

            JOptionPane.showMessageDialog(
                    null,
                    "ERRO AO EXCLUIR:\n",
                    "ERRO",
                    JOptionPane.ERROR_MESSAGE
            );

            e.printStackTrace();
        }
    }

