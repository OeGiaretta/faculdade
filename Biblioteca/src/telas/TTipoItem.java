    public void salvar() {
        Tipoitem t = new Tipoitem();
        t.setIdtipoitem(Integer.parseInt(campo2.getText()));
        t.setDescricao(campo3.getText().toUpperCase());
        t.setQtddiasprazo(Integer.parseInt(campo4.getText()));
        t.setVlrmulta(new BigDecimal(campo5.getText().replace(",", ".")));
        try {
            dao.salvar(t);
            JOptionPane.showMessageDialog(null, "TIPO DE ITEM SALVO COM SUCESSO");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e, "ERRO", JOptionPane.ERROR_MESSAGE);
        }
        limpar();
    }

    public void consultar() {
        int chave = Integer.parseInt(campo2.getText());
        Object obj1 = new Object();
        try {
            obj1 = dao.consultar("Tipoitem.findByIdtipoitem", "idtipoitem", chave);
            Tipoitem t = (Tipoitem) obj1;
            campo3.setText(t.getDescricao());
            campo4.setText(String.valueOf(t.getQtddiasprazo()));    
            campo5.setText(t.getVlrmulta().setScale(2).toString().replace(".", ","));
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "TIPO DE ITEM NÃO EXISTE", "ERRO", 0);
        }
    }
    
    public void excluir() {
        int chave = Integer.parseInt(campo2.getText());
        try {
            dao.excluir("Tipoitem.findByIdtipoitem", "idtipoitem", chave);
            JOptionPane.showMessageDialog(null, "TIPO DE ITEM EXCLUIDO COM SUCESSO");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "TIPO DE ITEM NÃO EXISTE", "ERRO", 0);
        }
        limpar();
    }

    public void limpar() {
        campo2.setText("");
        campo3.setText("");
        campo4.setText("");
        campo5.setText("");
    }

    public void sair() {
        dispose();
    }
