    public void salvar() {
        Classificacao c = new Classificacao();
        c.setIdclassificacao(Integer.parseInt(campo2.getText()));   
        c.setDescricao(campo3.getText().toUpperCase());
        
        try {
            dao.salvar(c);
            JOptionPane.showMessageDialog(null, "CLASSIFICAÇÃO DE ITEM SALVO COM SUCESSO");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e, "ERRO", JOptionPane.ERROR_MESSAGE);
        }
        limpar();
    }

    public void consultar() {
        int chave = Integer.parseInt(campo2.getText());
        Object obj1 = new Object();
        try {
            obj1 = dao.consultar("Classificacao.findByIdclassificacao", "idclassificacao", chave);
            Classificacao c = (Classificacao) obj1;
            campo3.setText(c.getDescricao());
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "CLASSIFICAÇÃO DE ITEM NÃO EXISTE", "ERRO", 0);
        }
    }

    public void excluir() {
        int chave = Integer.parseInt(campo2.getText());
        try {
            dao.excluir("Classificacao.findByIdclassificacao", "idclassificacao", chave);
            JOptionPane.showMessageDialog(null, "CLASSIFICAÇÃO DE ITEM EXCLUIDO COM SUCESSO");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "CLASSIFICAÇÃO DE ITEM NÃO EXISTE", "ERRO", 0);
        }
        limpar();
    }

    public void limpar() {
        campo2.setText("");
        campo3.setText("");
    }

    public void sair() {
        dispose();
    }
